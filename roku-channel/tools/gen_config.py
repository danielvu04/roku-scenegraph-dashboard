#!/usr/bin/env python3
"""Turn the shared config.json into source/generated_config.brs.

A Roku channel can only read files inside its own package, so the relevant
settings are baked in at build time. Lookup order:

    ../config.json  ->  ../config.example.json  ->  built-in defaults

Usage: python3 tools/gen_config.py [--config PATH]
"""

import argparse
import glob
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
CHANNEL = os.path.dirname(HERE)
PROJECT = os.path.dirname(CHANNEL)
OUT = os.path.join(CHANNEL, "source", "generated_config.brs")

DEFAULTS = {
    "location": {"name": "Minneapolis", "lat": 44.98, "lon": -93.27},
    "units": "fahrenheit",
    "clock_24h": False,
    "background_seconds": 45,
}


def strip_json_comments(text):
    """Allow // line comments (the SPEC example uses them) outside strings."""
    out, i, in_str, n = [], 0, False, len(text)
    while i < n:
        c = text[i]
        if in_str:
            out.append(c)
            if c == "\\" and i + 1 < n:
                out.append(text[i + 1])
                i += 1
            elif c == '"':
                in_str = False
        elif c == '"':
            in_str = True
            out.append(c)
        elif text.startswith("//", i):
            while i < n and text[i] != "\n":
                i += 1
            continue
        else:
            out.append(c)
        i += 1
    return "".join(out)


def load_config(explicit):
    candidates = [explicit] if explicit else [
        os.path.join(PROJECT, "config.json"),
        os.path.join(PROJECT, "config.example.json"),
    ]
    for path in candidates:
        if path and os.path.isfile(path):
            with open(path, encoding="utf-8") as f:
                try:
                    return json.loads(strip_json_comments(f.read())), path
                except json.JSONDecodeError as e:
                    sys.exit("gen_config: %s is not valid JSON: %s" % (path, e))
    return {}, None


def num(value, default, lo, hi):
    try:
        v = float(value)
    except (TypeError, ValueError):
        return default
    return v if lo <= v <= hi else default


def brs_string(s):
    # BrightScript strings have no backslash escapes; quotes are doubled.
    s = re.sub(r"[\x00-\x1f\x7f]", " ", str(s))
    return '"' + s.replace('"', '""') + '"'


def brs_float(v):
    text = repr(float(v))
    return text if "e" not in text else "%.6f" % v


def build(cfg):
    loc = cfg.get("location") or {}
    if not isinstance(loc, dict):
        loc = {}
    d = DEFAULTS
    units = str(cfg.get("units", d["units"])).lower()
    if units not in ("fahrenheit", "celsius"):
        units = d["units"]
    return {
        "name": str(loc.get("name") or d["location"]["name"])[:40],
        "lat": num(loc.get("lat"), d["location"]["lat"], -90, 90),
        "lon": num(loc.get("lon"), d["location"]["lon"], -180, 180),
        "units": units,
        "clock24h": bool(cfg.get("clock_24h", d["clock_24h"])),
        "bridgeUrl": ("http://%s:%d" % (str(cfg.get("bridge_host") or "").strip(), int(num(cfg.get("bridge_port"), 8787, 1, 65535)))) if str(cfg.get("bridge_host") or "").strip() else "",
        "backgroundSource": "photos" if str(cfg.get("background_source", "all")).lower() == "photos" else "all",
        # clamp rather than reject: crossfades take ~2.5 s
        "bgSeconds": int(min(3600, max(10, num(cfg.get("background_seconds"),
                                               d["background_seconds"], -1e9, 1e9)))),
    }


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--config", help="explicit config.json path")
    args = ap.parse_args()

    raw, src = load_config(args.config)
    c = build(raw)
    patterns = ("local_bg_*.jpg",) if c["backgroundSource"] == "photos" else ("bg_*.jpg", "local_bg_*.jpg")
    bgs = sorted(os.path.basename(p) for pat in patterns
                 for p in glob.glob(os.path.join(CHANNEL, "images", pat)))
    bg_list = ", ".join(brs_string("pkg:/images/" + b) for b in bgs)

    lines = [
        "' AUTO-GENERATED by tools/gen_config.py from %s - do not edit."
        % (os.path.relpath(src, CHANNEL) if src else "built-in defaults"),
        "' Re-run tools/build.sh after changing config.json.",
        "",
        "function GetCouchConfig() as Object",
        "    return {",
        "        locationName: %s" % brs_string(c["name"]),
        "        lat: %s" % brs_float(c["lat"]),
        "        lon: %s" % brs_float(c["lon"]),
        "        units: %s" % brs_string(c["units"]),
        "        clock24h: %s" % ("true" if c["clock24h"] else "false"),
        "        backgroundSeconds: %d" % c["bgSeconds"],
        "        bridgeUrl: %s" % brs_string(c["bridgeUrl"]),
        "        backgrounds: [%s]" % bg_list,
        "    }",
        "end function",
        "",
    ]
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print("gen_config: wrote %s (%s, %d backgrounds)"
          % (os.path.relpath(OUT, CHANNEL), src and os.path.basename(src) or "defaults", len(bgs)))


if __name__ == "__main__":
    main()
